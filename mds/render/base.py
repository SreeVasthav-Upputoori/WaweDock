"""Renderer-independent viewer interface.

The GUI talks only to ``ViewerBackend``; a different rendering technology (PyMOL, VTK, ...)
can be supported by providing another implementation of the same methods.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Protocol

REPRESENTATIONS = ("cartoon", "ribbon", "backbone", "sticks", "ball-and-stick", "lines",
                   "spheres", "surface")
COLOR_SCHEMES = ("element", "chain", "residue", "secondary structure", "spectrum", "object")
MEASURE_MODES = ("none", "distance", "angle", "dihedral")


class ViewerBackend(Protocol):
    def add_object(self, name: str, data: str, fmt: str, kind: str = "protein") -> None: ...
    def remove_object(self, name: str) -> None: ...
    def set_visible(self, name: str, visible: bool) -> None: ...
    def set_representation(self, name: str, representation: str) -> None: ...
    def set_color_scheme(self, name: str, scheme: str) -> None: ...
    def zoom_to(self, name: str | None = None) -> None: ...
    def show_residues_around(self, ligand: str, cutoff: float, protein: str) -> None: ...
    def clear_residue_selection(self) -> None: ...
    def show_box(self, center: tuple[float, float, float], size: tuple[float, float, float]) -> None: ...
    def clear_box(self) -> None: ...
    def set_measure_mode(self, mode: str) -> None: ...
    def clear_measurements(self) -> None: ...
    def label_residues(self, enabled: bool) -> None: ...
    def set_background(self, dark: bool) -> None: ...
    def export_image(self, path: str, scale: int = 3) -> None: ...

    # Residue-level pick selection ("Discovery Studio" style, see viewer.html)
    def clear_selection(self) -> None: ...
    def expand_selection_to_chain(self) -> None: ...
    def invert_selection(self) -> None: ...
    def set_selection(self, detail: dict) -> None: ...

    # signals/callbacks provided by implementations:
    on_atom_info: Callable[[str], None]
    on_measurement: Callable[[str], None]
    on_selection: Callable[[dict, str], None]
